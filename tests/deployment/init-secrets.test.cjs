const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const os = require('node:os')
const crypto = require('node:crypto')
const { parseEnv } = require('node:util')
const { initialize } = require('../../scripts/init-secrets')

function fixture(t) {
  const parent = path.resolve(os.tmpdir())
  const root = fs.mkdtempSync(path.join(parent, 'finvault-init-'))
  t.after(() => {
    assert.equal(path.dirname(root), parent)
    assert.ok(path.basename(root).startsWith('finvault-init-'))
    fs.rmSync(root, { recursive: true, force: true })
  })
  fs.copyFileSync(path.resolve(__dirname, '../../.env.example'), path.join(root, '.env.example'))
  return root
}
test('fresh environment has matching production keys and consistent credentials; reruns preserve them', t => {
  const root = fixture(t)
  initialize(root)
  const envPath = path.join(root, '.env')
  const first = fs.readFileSync(envPath, 'utf8')
  const config = parseEnv(first)
  const key = fs.readFileSync(path.join(root, 'secrets/gateway_private.pem'))
  const publicKey = fs.readFileSync(path.join(root, 'secrets/gateway_public.pem'), 'utf8')
  assert.equal(crypto.createPublicKey(key).export({ type: 'spki', format: 'pem' }), publicKey)
  assert.equal(crypto.createPrivateKey(key).asymmetricKeyDetails.namedCurve, 'prime256v1')
  for (const [name, file] of [['POSTGRES_PASSWORD', 'postgres_password.txt'], ['RABBITMQ_PASS', 'rabbitmq_pass.txt']]) {
    assert.equal(config[name], fs.readFileSync(path.join(root, 'secrets', file), 'utf8').trim())
    assert.equal(config[name].length, 64)
  }
  assert.equal(config.S3_SECRET_ACCESS_KEY.length, 64)
  initialize(root)
  assert.equal(fs.readFileSync(envPath, 'utf8'), first)
  assert.deepEqual(fs.readFileSync(path.join(root, 'secrets/gateway_private.pem')), key)
})
test('existing credentials are kept and database URLs encode special characters', t => {
  const root = fixture(t)
  fs.writeFileSync(path.join(root, '.env'), "POSTGRES_PASSWORD='existing:p@ss/word'\nRABBITMQ_PASS=existing-broker\n")
  initialize(root)
  const config = parseEnv(fs.readFileSync(path.join(root, '.env'), 'utf8'))
  assert.equal(config.POSTGRES_PASSWORD, 'existing:p@ss/word')
  assert.equal(config.POSTGRES_PASSWORD_URLENCODED, encodeURIComponent(config.POSTGRES_PASSWORD))
  assert.equal(config.RABBITMQ_PASS, 'existing-broker')
})
test('conflicting credentials and mismatched keys are rejected without replacing existing values', t => {
  const root = fixture(t)
  initialize(root)
  const secretPath = path.join(root, 'secrets/postgres_password.txt')
  const original = fs.readFileSync(secretPath)
  fs.writeFileSync(secretPath, 'different-password')
  assert.throws(() => initialize(root), /differs between/)
  assert.equal(fs.readFileSync(secretPath, 'utf8'), 'different-password')
  fs.writeFileSync(secretPath, original)
  const publicPath = path.join(root, 'secrets/gateway_public.pem')
  const other = crypto.generateKeyPairSync('ec', { namedCurve: 'prime256v1' }).publicKey.export({ type: 'spki', format: 'pem' })
  fs.writeFileSync(publicPath, other)
  assert.throws(() => initialize(root), /do not match/)
  assert.equal(fs.readFileSync(publicPath, 'utf8'), other)
})
